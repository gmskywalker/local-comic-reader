    $form.Text = '本地漫画网页生成器'
    $form.StartPosition = 'CenterScreen'
    $form.Size = New-Object System.Drawing.Size(1040, 760)
    $form.MinimumSize = New-Object System.Drawing.Size(860, 660)
    $form.Font = New-Object System.Drawing.Font('Microsoft YaHei UI', 10)

