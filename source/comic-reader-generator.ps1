    if ($null -ne $PreviousChapter) {
        $previousHref = ConvertTo-UrlSegment $PreviousChapter.ReaderFile
        $previousTop = '<a href="' + (ConvertTo-HtmlText $previousHref) + '">← 上一话</a>'
        $previousBottom = $previousTop
    }
    if ($null -ne $NextChapter) {
        $nextHref = ConvertTo-UrlSegment $NextChapter.ReaderFile
        $nextTop = '<a href="' + (ConvertTo-HtmlText $nextHref) + '">下一话 →</a>'
        $nextBottom = $nextTop
    }

    $comicSegment = ConvertTo-UrlSegment $Comic.Name
    $readerConfig = [ordered]@{
        comicKey = $Comic.Key
        chapterKey = $Chapter.Key
        comicTitle = $Comic.Name
        chapterTitle = $Chapter.Name
        totalPages = $Chapter.ImageCount
        rootHref = $comicSegment + '/' + (ConvertTo-UrlSegment $Chapter.ReaderFile)
        comicHref = ConvertTo-UrlSegment $Chapter.ReaderFile
        previousHref = $previousHref
        nextHref = $nextHref
    }

    $template = Get-ReaderTemplate
    $pageTitle = $Comic.Name + ' · ' + $Chapter.Name
    $content = $template.Replace('__PAGE_TITLE__', (ConvertTo-HtmlText $pageTitle))
    $content = $content.Replace('__CHAPTER_LABEL__', (ConvertTo-HtmlText $Chapter.ChapterLabel))
    $content = $content.Replace('__CHAPTER_COUNT__', [string]$Comic.ChapterCount)
    $content = $content.Replace('__LAUNCHER_URL__', (ConvertTo-UrlSegment $script:LauncherFileName))
    $content = $content.Replace('__PREV_TOP__', $previousTop)
    $content = $content.Replace('__PREV_BOTTOM__', $previousBottom)
    $content = $content.Replace('__NEXT_TOP__', $nextTop)
    $content = $content.Replace('__NEXT_BOTTOM__', $nextBottom)
    $content = $content.Replace('__IMAGES__', $imagesHtml.ToString().TrimEnd())
    $content = $content.Replace('__TOTAL__', [string]$Chapter.ImageCount)
    $content = $content.Replace('__READER_CONFIG__', (ConvertTo-SafeJson $readerConfig))
    $content = $content.Replace('__THEME_CONTROLS__', (Get-ThemeControls).TrimEnd())
    $content = $content.Replace('__THEME_RUNTIME__', (Get-ThemeRuntime).TrimEnd())
    $path = Join-Path $Comic.FullName $Chapter.ReaderFile
    Write-GeneratedFile -Path $path -Content $content
}

function New-ComicPages {
    param([object]$Comic)
    New-ComicIndexPage -Comic $Comic
    for ($index = 0; $index -lt $Comic.Chapters.Count; $index++) {
        $previous = $null
        $next = $null
        if ($index -gt 0) { $previous = $Comic.Chapters[$index - 1] }
        if ($index -lt ($Comic.Chapters.Count - 1)) { $next = $Comic.Chapters[$index + 1] }
        New-ChapterReaderPage -Comic $Comic -Chapter $Comic.Chapters[$index] -PreviousChapter $previous -NextChapter $next
    }
}

function Remove-LegacyChapterPages {
    param([object]$Comic)
    $removed = 0
    foreach ($chapter in $Comic.Chapters) {
        if ($chapter.IsRootChapter) {
            continue
        }
        $legacyPath = Join-Path $chapter.FullName 'index.html'
        if (-not (Test-Path -LiteralPath $legacyPath -PathType Leaf)) {
            continue
        }
        $legacyHtml = [System.IO.File]::ReadAllText($legacyPath, [System.Text.Encoding]::UTF8)
        if (-not $legacyHtml.StartsWith($script:GeneratorMarker)) {
            Write-Host ('  警告：保留非本工具生成的旧文件：' + $legacyPath) -ForegroundColor Yellow
            continue
        }
        Remove-Item -LiteralPath $legacyPath
        $removed++
    }
    return $removed
}

function Test-GeneratedComic {
    param([object]$Comic)
    $problems = New-Object 'System.Collections.Generic.List[string]'
    $comicIndex = Join-Path $Comic.FullName 'index.html'
    if (-not (Test-Path -LiteralPath $comicIndex -PathType Leaf)) {
        $problems.Add('缺少漫画章节目录 index.html')
    }
    else {
        $indexHtml = [System.IO.File]::ReadAllText($comicIndex, [System.Text.Encoding]::UTF8)
        $expectedCover = 'src="' + (ConvertTo-HtmlText $Comic.CoverRelativeHref) + '"'
        if (-not $indexHtml.Contains($expectedCover)) {
            $problems.Add(('章节目录没有引用核验通过的封面：' + $Comic.CoverRelativeHref))
        }
    }
    foreach ($chapter in $Comic.Chapters) {
        $readerPath = Join-Path $Comic.FullName $chapter.ReaderFile
        if (-not (Test-Path -LiteralPath $readerPath -PathType Leaf)) {
            $problems.Add(($chapter.Name + '：缺少 ' + $chapter.ReaderFile))
            continue
        }
        $html = [System.IO.File]::ReadAllText($readerPath, [System.Text.Encoding]::UTF8)
        $imageTagCount = ([regex]::Matches($html, '<img class="page" ')).Count
        if ($imageTagCount -ne $chapter.ImageCount) {
            $problems.Add(('{0}：网页引用 {1} 张，但文件夹有 {2} 张' -f $chapter.Name, $imageTagCount, $chapter.ImageCount))
        }
        foreach ($image in $chapter.Images) {
            $expectedSrc = Get-ChapterImageHref -Chapter $chapter -Image $image
            $expected = 'src="' + (ConvertTo-HtmlText $expectedSrc) + '"'
            if (-not $html.Contains($expected)) {
                $problems.Add(('{0}：网页遗漏 {1}' -f $chapter.Name, $image.Name))
            }
        }
    }
    return @($problems)
}

function Invoke-ComicUpdate {
    param(
        [string]$LibraryRoot,
        [string[]]$PreviousSelectedNames,
        [string[]]$CheckedNames,
        [ValidateSet('All', 'AddOnly')][string]$UpdateMode,
        [bool]$OpenAfterGenerate,
        [switch]$AuditOnlyMode
    )
    $selectionPlan = Resolve-UpdateSelection -PreviousNames $PreviousSelectedNames -CheckedNames $CheckedNames -UpdateMode $UpdateMode
    $selectedNames = @($selectionPlan.SelectedNames)
    $namesToGenerate = @($selectionPlan.NamesToGenerate)
    if ($selectedNames.Count -eq 0) { throw '没有选择任何漫画。' }
    if ($UpdateMode -eq 'AddOnly' -and $namesToGenerate.Count -eq 0) { throw '没有发现本次新勾选的漫画。' }

    $preservedCards = @{}
    $namesToAudit = @($selectedNames)
    if ($UpdateMode -eq 'AddOnly') {
        $preservedCards = Get-ExistingRootCards -LibraryRoot $LibraryRoot -ComicNames $PreviousSelectedNames
        $namesToAudit = @($namesToGenerate)
        Write-Info ('快速加入模式：保留 {0} 部既有漫画，仅核验并生成 {1} 部新漫画。' -f $PreviousSelectedNames.Count, $namesToAudit.Count)
    }

    $audited = @()
    $failed = @()
    for ($auditIndex = 0; $auditIndex -lt $namesToAudit.Count; $auditIndex++) {
        $name = $namesToAudit[$auditIndex]
        $path = Join-Path $LibraryRoot $name
        if (-not (Test-Path -LiteralPath $path -PathType Container)) {
            $failed += [pscustomobject]@{ Name = $name; Errors = @('文件夹不存在：' + $path) }
            Write-Bad ('核验失败：' + $name + '（文件夹不存在）')
            continue
        }
        Write-Info ('正在核验 {0}/{1}：{2}' -f ($auditIndex + 1), $namesToAudit.Count, $name)
        $audit = Get-ComicAudit -ComicDirectory (Get-Item -LiteralPath $path)
        if ($audit.IsValid) {
            Write-Good ('核验通过：{0} 话，{1} 张图片' -f $audit.ChapterCount, $audit.TotalImages)
            foreach ($warning in $audit.Warnings) { Write-Host ('  警告：' + $warning) -ForegroundColor Yellow }
            $audited += $audit
        }
        else {
            Write-Bad ('核验失败：' + $name)
            foreach ($problem in $audit.Errors) { Write-Host ('  - ' + $problem) -ForegroundColor Red }
            $failed += $audit
        }
    }

    if ($AuditOnlyMode) {
        if ($failed.Count -eq 0) { Write-Good '只读核验完成，未写入网页。' }
        return [pscustomobject]@{
            PersistedSelectedNames = @($selectedNames)
            Generated = @()
            Failed = @($failed)
            GeneratedCount = 0
            FailedCount = $failed.Count
            ChapterCount = 0
            ImageCount = 0
            LauncherCount = 0
            LauncherPath = ''
        }
    }
    if ($audited.Count -eq 0) { throw '没有任何漫画通过核验，未生成网页。' }
    $generationTargets = @($audited | Where-Object { $namesToGenerate -contains $_.Name })
    if ($generationTargets.Count -eq 0) { throw '本次需要生成的漫画均未通过核验，未修改网页。' }

    $generated = @()
    for ($generationIndex = 0; $generationIndex -lt $generationTargets.Count; $generationIndex++) {
        $comic = $generationTargets[$generationIndex]
        try {
            Write-Info ('正在生成 {0}/{1}：{2}' -f ($generationIndex + 1), $generationTargets.Count, $comic.Name)
            New-ComicPages -Comic $comic
            $verifyProblems = @(Test-GeneratedComic -Comic $comic)
            if ($verifyProblems.Count -gt 0) { throw ('生成后复核失败：' + ($verifyProblems -join '；')) }
            $removedLegacyPages = Remove-LegacyChapterPages -Comic $comic
            if ($removedLegacyPages -gt 0) { Write-Info ('已移除旧位置的章节 index.html：' + $removedLegacyPages + ' 个') }
            $generated += $comic
            Write-Good ('生成并复核完成：' + $comic.Name)
        }
        catch {
            Write-Bad ($comic.Name + '：' + $_.Exception.Message)
            $failed += [pscustomobject]@{ Name = $comic.Name; Errors = @($_.Exception.Message) }
        }
    }

    if ($generated.Count -eq 0) { throw '没有任何漫画成功生成，未更新总打开器。' }
    $launcherComics = @($generated | Group-Object Name | ForEach-Object { $_.Group[0] })
    $persistedSelectedNames = if ($UpdateMode -eq 'AddOnly') {
        @($PreviousSelectedNames + @($generated | ForEach-Object { $_.Name }) | Select-Object -Unique)
    }
    else { @($launcherComics | ForEach-Object { $_.Name }) }
    $launcherCount = $preservedCards.Count + $launcherComics.Count
    Write-Info '正在更新并复核总打开器……'
    $launcherPath = New-RootPage -Comics $launcherComics -LibraryRoot $LibraryRoot -SelectedNames $persistedSelectedNames -OpenAfterGenerate $OpenAfterGenerate -PreservedCards $preservedCards
    $launcherHtml = [System.IO.File]::ReadAllText($launcherPath, [System.Text.Encoding]::UTF8)
    $rootCardCount = ([regex]::Matches($launcherHtml, '<article class="card" ')).Count
    if ($rootCardCount -ne $launcherCount) { throw "总打开器复核失败：应有 $launcherCount 部漫画，实际有 $rootCardCount 个卡片。" }

    $chapterCount = [int](($generated | Measure-Object ChapterCount -Sum).Sum)
    $imageCount = [int](($generated | Measure-Object TotalImages -Sum).Sum)
    Write-Good ('总打开器已更新：' + $launcherPath)
    return [pscustomobject]@{
        PersistedSelectedNames = @($persistedSelectedNames)
        Generated = @($generated)
        Failed = @($failed)
        GeneratedCount = $generated.Count
        FailedCount = $failed.Count
        ChapterCount = $chapterCount
        ImageCount = $imageCount
        LauncherCount = $launcherCount
        LauncherPath = $launcherPath
    }
}

try {
    $scriptPath = if (-not [string]::IsNullOrWhiteSpace($env:LOCAL_COMIC_TOOL_PATH)) {
        $env:LOCAL_COMIC_TOOL_PATH
    }
    else {
        $MyInvocation.MyCommand.Path
    }
    if ([string]::IsNullOrWhiteSpace($scriptPath)) {
        throw '无法确定生成器脚本所在目录。'
    }
    $scriptDirectory = [System.IO.Path]::GetDirectoryName($scriptPath)
    if ([string]::IsNullOrWhiteSpace($RootPath)) {
        $rootCandidate = $scriptDirectory
    }
    elseif ([System.IO.Path]::IsPathRooted($RootPath)) {
        $rootCandidate = $RootPath
    }
    else {
        $rootCandidate = Join-Path $scriptDirectory $RootPath
    }
    $resolvedRoot = (Resolve-Path -LiteralPath $rootCandidate).Path
    if (-not (Test-Path -LiteralPath $resolvedRoot -PathType Container)) {
        throw "漫画根目录不存在：$resolvedRoot"
    }
    if ([string]::IsNullOrWhiteSpace($ConfigPath)) {
        $ConfigPath = Join-Path $resolvedRoot $script:ConfigFileName
    }
    elseif (-not [System.IO.Path]::IsPathRooted($ConfigPath)) {
        $ConfigPath = [System.IO.Path]::GetFullPath((Join-Path $resolvedRoot $ConfigPath))
    }
    else {
        $ConfigPath = [System.IO.Path]::GetFullPath($ConfigPath)
    }

    Write-Info ('漫画根目录：' + $resolvedRoot)
    $configuration = Get-Configuration -LegacyPath $ConfigPath -LibraryRoot $resolvedRoot
    $candidates = @(Get-AllCandidates -LibraryRoot $resolvedRoot)

    $selectedNames = @($configuration.selected)
    $staleSelectedNames = @($selectedNames | Where-Object {
        -not (Test-Path -LiteralPath (Join-Path $resolvedRoot $_) -PathType Container)
    })
    if ($staleSelectedNames.Count -gt 0) {
        Write-Info ('已从选择记录中移除不存在的文件夹：' + ($staleSelectedNames -join '、'))
        $selectedNames = @($selectedNames | Where-Object {
            Test-Path -LiteralPath (Join-Path $resolvedRoot $_) -PathType Container
        })
    }
    $previousSelectedNames = @($selectedNames)
    $openAfterGenerate = [bool]$configuration.openAfterGenerate
    if (-not $NonInteractive) {
        $uiResult = Show-ComicSelector -LibraryRoot $resolvedRoot -Candidates $candidates -SelectedNames $selectedNames -OpenAfterGenerate $openAfterGenerate -SkipOpen:$SkipOpen -SmokeTest:$UiSmokeTest
        exit ([int]$uiResult.ExitCode)
    }

    $result = Invoke-ComicUpdate -LibraryRoot $resolvedRoot -PreviousSelectedNames $previousSelectedNames -CheckedNames $selectedNames -UpdateMode 'All' -OpenAfterGenerate $openAfterGenerate -AuditOnlyMode:$AuditOnly
    if ($AuditOnly) {
        if ($result.FailedCount -gt 0) { exit 2 }
        exit 0
    }
    Write-Host ''
    Write-Host ('本次生成：{0} 部漫画，{1} 话，{2} 张图片；书架共 {3} 部。' -f $result.GeneratedCount, $result.ChapterCount, $result.ImageCount, $result.LauncherCount) -ForegroundColor Green
    if ($result.FailedCount -gt 0) {
        Write-Host ('失败：{0} 部漫画。错误已显示在上方，其他漫画不受影响。' -f $result.FailedCount) -ForegroundColor Yellow
        exit 2
    }
    exit 0
}
catch {
    $script:ProgressLabel = $null
    Write-Bad $_.Exception.Message
    if (-not $NonInteractive -and -not $UiSmokeTest) {
        Add-Type -AssemblyName System.Windows.Forms
        [System.Windows.Forms.MessageBox]::Show($_.Exception.Message, '漫画更新器错误', [System.Windows.Forms.MessageBoxButtons]::OK, [System.Windows.Forms.MessageBoxIcon]::Error) | Out-Null
    }
    exit 1
}
