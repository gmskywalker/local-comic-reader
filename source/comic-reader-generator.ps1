function Get-NaturalNameSortKey {
    param([string]$Name)
    return [regex]::Replace($Name, '\d+', {
        param($match)
        return $match.Value.PadLeft(24, '0')
    })
}

function Get-CompositeImageRecord {
    param([System.IO.FileInfo]$File)
    $match = [regex]::Match($File.BaseName, '^(?<prefix>.*\D)(?<page>\d+)$')
    if (-not $match.Success) { return $null }
    $page = [int64]0
    if (-not [int64]::TryParse($match.Groups['page'].Value, [ref]$page)) { return $null }
    return [pscustomobject]@{
        File = $File
        Prefix = $match.Groups['prefix'].Value
        Page = $page
    }
}

function Get-SequenceDisplayName {
    param([string]$Prefix)
    $display = $Prefix.TrimEnd([char[]]' _-.~')
    if ([string]::IsNullOrWhiteSpace($display)) { return $Prefix }
    return $display
}

function Get-FlexibleImageSequence {
    param(
        [System.IO.FileInfo[]]$Files,
        [string]$Context
    )
    $errors = New-Object 'System.Collections.Generic.List[string]'
    $warnings = New-Object 'System.Collections.Generic.List[string]'
    $images = @($Files)
    if ($images.Count -eq 0) {
        $errors.Add(($Context + '：没有图片'))
        return [pscustomobject]@{ Images = @(); Errors = @($errors); Warnings = @($warnings); Mode = 'Empty' }
    }
    foreach ($image in $images) {
        if ($image.Length -eq 0) { $errors.Add(($Context + '：图片是空文件：' + $image.Name)) }
    }

    $numericRecords = @()
    $allNumeric = $true
    foreach ($image in $images) {
        if ($image.BaseName -notmatch '^\d+$') { $allNumeric = $false; break }
        $number = [int64]0
        if (-not [int64]::TryParse($image.BaseName, [ref]$number)) {
            $errors.Add(($Context + '：图片编号过大或无效：' + $image.Name))
            continue
        }
        $numericRecords += [pscustomobject]@{ File = $image; Page = $number; Prefix = '' }
    }
    if ($allNumeric) {
        $duplicates = @($numericRecords | Group-Object Page | Where-Object Count -gt 1)
        foreach ($duplicate in $duplicates) {
            $errors.Add(('{0}：图片编号 {1} 重复（{2}）' -f $Context, $duplicate.Name, (($duplicate.Group.File.Name) -join '、')))
        }
        $orderedNumbers = @($numericRecords.Page | Sort-Object -Unique)
        if ($orderedNumbers.Count -gt 0 -and $orderedNumbers[0] -ne 1) {
            $errors.Add(('{0}：第一张图片应为 0001，实际编号为 {1}' -f $Context, $orderedNumbers[0]))
        }
        if ($orderedNumbers.Count -gt 0) {
            $numberMap = @{}
            foreach ($number in $orderedNumbers) { $numberMap[[string]$number] = $true }
            for ($number = 1; $number -le $orderedNumbers[-1]; $number++) {
                if (-not $numberMap.ContainsKey([string]$number)) {
                    $errors.Add(('{0}：缺少图片编号 {1:D4}' -f $Context, $number))
                }
            }
        }
        return [pscustomobject]@{
            Images = @($numericRecords | Sort-Object Page, @{ Expression = { $_.File.Name } } | ForEach-Object File)
            Errors = @($errors)
            Warnings = @($warnings)
            Mode = 'Numeric'
        }
    }

    $compositeRecords = @()
    foreach ($image in $images) {
        $record = Get-CompositeImageRecord -File $image
        if ($null -eq $record) { $compositeRecords = @(); break }
        $compositeRecords += $record
    }
    if ($compositeRecords.Count -eq $images.Count) {
        $orderedFiles = @()
        $groups = @($compositeRecords | Group-Object Prefix | Sort-Object {
            Get-NaturalNameSortKey -Name (Get-SequenceDisplayName -Prefix $_.Name)
        }, Name)
        foreach ($group in $groups) {
            $groupLabel = Get-SequenceDisplayName -Prefix $group.Name
            $duplicates = @($group.Group | Group-Object Page | Where-Object Count -gt 1)
            foreach ($duplicate in $duplicates) {
                $errors.Add(('{0}：分组 {1} 的页码 {2} 重复（{3}）' -f $Context, $groupLabel, $duplicate.Name, (($duplicate.Group.File.Name) -join '、')))
            }
            $orderedNumbers = @($group.Group.Page | Sort-Object -Unique)
            if ($orderedNumbers.Count -gt 0 -and $orderedNumbers[0] -notin @([int64]0, [int64]1)) {
                $errors.Add(('{0}：分组 {1} 应从 000 或 001 开始，实际从 {2} 开始' -f $Context, $groupLabel, $orderedNumbers[0]))
            }
            if ($orderedNumbers.Count -gt 0) {
                $numberMap = @{}
                foreach ($number in $orderedNumbers) { $numberMap[[string]$number] = $true }
                for ($number = $orderedNumbers[0]; $number -le $orderedNumbers[-1]; $number++) {
                    if (-not $numberMap.ContainsKey([string]$number)) {
                        $errors.Add(('{0}：分组 {1} 缺少页码 {2}' -f $Context, $groupLabel, $number))
                    }
                }
            }
            $orderedFiles += @($group.Group | Sort-Object Page, @{ Expression = { $_.File.Name } } | ForEach-Object File)
        }
        return [pscustomobject]@{
            Images = @($orderedFiles)
            Errors = @($errors)
            Warnings = @($warnings)
            Mode = 'Composite'
        }
    }

    $warnings.Add(($Context + '：无法可靠提取连续页码，已按文件名称自然排序；这种命名方式无法自动判断是否缺图。'))
    return [pscustomobject]@{
        Images = @($images | Sort-Object { Get-NaturalNameSortKey -Name $_.Name }, Name)
        Errors = @($errors)
        Warnings = @($warnings)
        Mode = 'NameSorted'
    }
}

function Get-RootImageLayout {
    param([System.IO.FileInfo[]]$Files)
    $images = @($Files)
    $standaloneZero = @($images | Where-Object { $_.BaseName -match '^0+$' })
    $records = @()
    $unrecognized = @()
    foreach ($image in $images) {
        if ($image.BaseName -match '^0+$') { continue }
        $record = Get-CompositeImageRecord -File $image
        if ($null -eq $record) { $unrecognized += $image } else { $records += $record }
    }
    $groups = @($records | Group-Object Prefix)
    if ($records.Count -eq 0 -or $unrecognized.Count -gt 0 -or $standaloneZero.Count -gt 1 -or $groups.Count -lt 2) {
        return [pscustomobject]@{ Recognized = $false; Groups = @(); CoverCandidate = $null }
    }

    $usedNames = @{}
    $resultGroups = @()
    foreach ($group in @($groups | Sort-Object {
        Get-NaturalNameSortKey -Name (Get-SequenceDisplayName -Prefix $_.Name)
    }, Name)) {
        $display = Get-SequenceDisplayName -Prefix $group.Name
        if ([string]::IsNullOrWhiteSpace($display)) { $display = '分组' }
        $baseDisplay = $display
        $suffix = 2
        while ($usedNames.ContainsKey($display.ToLowerInvariant())) {
            $display = $baseDisplay + ' (' + $suffix + ')'
            $suffix++
        }
        $usedNames[$display.ToLowerInvariant()] = $true
        $resultGroups += [pscustomobject]@{
            Name = $display
            Prefix = $group.Name
            Files = @($group.Group.File)
            NaturalSortKey = Get-NaturalNameSortKey -Name $display
        }
    }
    return [pscustomobject]@{
        Recognized = $true
        Groups = @($resultGroups | Sort-Object NaturalSortKey, Name)
        CoverCandidate = if ($standaloneZero.Count -eq 1) { $standaloneZero[0] } else { $null }
    }
}

