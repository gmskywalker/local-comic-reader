        $_.BaseName -ieq 'cover' -and $script:ImageExtensions -contains $_.Extension.ToLowerInvariant()
    } | Sort-Object {
        switch ($_.Extension.ToLowerInvariant()) {
            '.jpg' { 0 }
            '.jpeg' { 1 }
