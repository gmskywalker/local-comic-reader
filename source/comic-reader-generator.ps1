function ConvertTo-UrlSegment {
    param([string]$Value)
    return [System.Uri]::EscapeDataString($Value)
}

function ConvertTo-RelativeUrlPath {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return '' }
    return (([regex]::Split($Value, '[/\\]+') | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | ForEach-Object {
        ConvertTo-UrlSegment ([string]$_)
    }) -join '/')
}

function Test-SafeRelativePath {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value) -or [IO.Path]::IsPathRooted($Value)) { return $false }
    $parts = @([regex]::Split($Value, '[/\\]+') | Where-Object { $_ -ne '' })
    if ($parts.Count -eq 0) { return $false }
    foreach ($part in $parts) {
        if ($part -in @('.', '..') -or $part -match '[<>:"|?*]') { return $false }
    }
    return $true
}

function Resolve-SafeChildPath {
    param(
        [string]$Root,
        [string]$RelativePath
    )
    if (-not (Test-SafeRelativePath -Value $RelativePath)) { return '' }
    $rootFull = [IO.Path]::GetFullPath($Root).TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
    $candidate = [IO.Path]::GetFullPath((Join-Path $rootFull ($RelativePath -replace '/', [IO.Path]::DirectorySeparatorChar)))
    if (-not $candidate.StartsWith($rootFull + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) { return '' }
    return $candidate
}

function ConvertTo-SafeJson {
    param([AllowNull()][object]$Value, [int]$Depth = 10)
    $json = $Value | ConvertTo-Json -Depth $Depth -Compress
    return $json.Replace('</', '<\/')
}

function Get-StableKey {
    param([string]$Value)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $bytes = [System.Text.Encoding]::UTF8.GetBytes($Value)
        $hash = $sha.ComputeHash($bytes)
        return (($hash | ForEach-Object { $_.ToString('x2') }) -join '').Substring(0, 20)
    }
    finally {
        $sha.Dispose()
    }
}

function ConvertTo-ChapterNumberInfo {
    param([AllowNull()][object]$Value)
    if ($null -eq $Value) { return $null }
    $text = ([string]$Value).Trim()
    if ($text -notmatch '^\d+(?:\.\d+)?$') { return $null }
    $number = [decimal]0
    $parsed = [decimal]::TryParse(
        $text,
        [Globalization.NumberStyles]::AllowDecimalPoint,
        [Globalization.CultureInfo]::InvariantCulture,
        [ref]$number
    )
    if (-not $parsed -or $number -le 0) { return $null }
    return [pscustomobject]@{
        Text = $number.ToString('0.############################', [Globalization.CultureInfo]::InvariantCulture)
        Value = $number
    }
}

function Get-ChapterNumberFromName {
    param([string]$Name)
    $match = [regex]::Match($Name, '^第\s*(\d+(?:\.\d+)?)\s*[话話](?<qualifier>.*)$')
    if (-not $match.Success) { return $null }
    $numberInfo = ConvertTo-ChapterNumberInfo -Value $match.Groups[1].Value
    if ($null -eq $numberInfo) { return $null }
    $qualifier = $match.Groups['qualifier'].Value.Trim()
    return [pscustomobject]@{
        Text = $numberInfo.Text
        Value = $numberInfo.Value
        Qualifier = $qualifier
        QualifierKey = ([regex]::Replace($qualifier, '\s+', '')).ToLowerInvariant()
        HasQualifier = -not [string]::IsNullOrWhiteSpace($qualifier)
    }
}

