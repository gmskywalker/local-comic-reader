}

function Get-WindowsChapterNameMatchKey {
    param([AllowNull()][object]$Value)
    if ($null -eq $Value) { return '' }
    $text = ([string]$Value).Normalize([Text.NormalizationForm]::FormKC)
    # Windows/下载器会把 ?、: 等非法字符换成全角形式，并移除末尾空格和句点。
    # FormKC 可统一全角/半角形式；循环修剪模拟 Windows 对目录名末尾的处理。
    while ($text.Length -gt 0 -and ([char]::IsWhiteSpace($text[$text.Length - 1]) -or $text[$text.Length - 1] -eq '.')) {
        $text = $text.Substring(0, $text.Length - 1)
    }
    return $text
}

function Get-ComicMetadata {
    param([string]$ComicPath)
    $metadataPath = Join-Path $ComicPath '元数据.json'
    $result = [ordered]@{
        Title = ''
        Author = ''
        Description = ''
        MetadataWarning = ''
        ReadingOrderEnabled = $false
        ReadingOrderMap = @{}
        ReadingOrderNormalizedMap = @{}
        ReadingOrderError = ''
    }
    if (-not (Test-Path -LiteralPath $metadataPath -PathType Leaf)) {
        return [pscustomobject]$result
    }
    try {
        $raw = [System.IO.File]::ReadAllText($metadataPath, [System.Text.Encoding]::UTF8)
        $meta = $raw | ConvertFrom-Json
        $result.Title = Get-MetadataFieldText -Metadata $meta -Names @('name', 'title')
        $authorText = Get-MetadataFieldText -Metadata $meta -Names @('author', 'authors', 'artist', 'artists')
        $result.Author = ([regex]::Replace($authorText, '\s*\r?\n\s*', '、')).Trim('、')
        $result.Description = Get-MetadataFieldText -Metadata $meta -Names @('description', 'intro', 'summary', 'desc', '简介', '簡介')
        $organizerSchema = 0
        if ($null -ne $meta.PSObject.Properties['organizer'] -and
            $null -ne $meta.organizer -and
            $null -ne $meta.organizer.PSObject.Properties['schemaVersion']) {
            [void][int]::TryParse([string]$meta.organizer.schemaVersion, [ref]$organizerSchema)
        }
        $chapterInfos = @()
        if ($null -ne $meta.PSObject.Properties['chapterInfos']) {
            $chapterInfos = @($meta.chapterInfos)
        }
        if ($organizerSchema -ge 2 -or $chapterInfos.Count -gt 0) {
            $orderErrors = New-Object 'System.Collections.Generic.List[string]'
            $orderMap = @{}
            $normalizedOrderMap = @{}
            $usedOrders = @{}
            if ($chapterInfos.Count -eq 0) {
                $orderErrors.Add('新版整理器元数据中没有 chapterInfos。')
            }
            foreach ($chapterInfo in $chapterInfos) {
                $chapterFolder = ''
                if ($null -ne $chapterInfo.PSObject.Properties['chapterFolder']) {
                    $chapterFolder = [string]$chapterInfo.chapterFolder
                }
                elseif ($null -ne $chapterInfo.PSObject.Properties['chapterTitle']) {
                    $chapterFolder = [string]$chapterInfo.chapterTitle
                }
                $readingOrder = 0
                if ([string]::IsNullOrWhiteSpace($chapterFolder) -or
                    $null -eq $chapterInfo.PSObject.Properties['order'] -or
                    -not [int]::TryParse([string]$chapterInfo.order, [ref]$readingOrder) -or
                    $readingOrder -lt 1) {
                    $orderErrors.Add('存在缺少章节文件夹名或有效阅读顺序的 chapterInfos 项。')
                    continue
                }
                if ($orderMap.ContainsKey($chapterFolder)) {
                    $orderErrors.Add(('阅读顺序元数据中的章节重复：' + $chapterFolder))
                    continue
                }
                if ($usedOrders.ContainsKey([string]$readingOrder)) {
                    $orderErrors.Add(('阅读顺序元数据中的顺序重复：' + $readingOrder))
                    continue
                }
                $normalizedKey = Get-WindowsChapterNameMatchKey -Value $chapterFolder
                if ([string]::IsNullOrWhiteSpace($normalizedKey)) {
                    $orderErrors.Add(('阅读顺序元数据中的章节名称无法用于匹配：' + $chapterFolder))
                    continue
                }
                if ($normalizedOrderMap.ContainsKey($normalizedKey)) {
                    $otherFolder = [string]$normalizedOrderMap[$normalizedKey].Folder
                    if (-not $otherFolder.Equals($chapterFolder, [StringComparison]::OrdinalIgnoreCase)) {
                        $orderErrors.Add(('章节名称按 Windows 文件名规则处理后发生重复：{0}、{1}' -f $otherFolder, $chapterFolder))
                        continue
                    }
                }
                $orderMap[$chapterFolder] = $readingOrder
                $normalizedOrderMap[$normalizedKey] = [pscustomobject]@{ Folder = $chapterFolder; Order = $readingOrder }
                $usedOrders[[string]$readingOrder] = $true
            }
            if ($orderErrors.Count -gt 0) {
                $result.ReadingOrderError = ($orderErrors -join '；')
            }
            else {
                $result.ReadingOrderEnabled = $true
                $result.ReadingOrderMap = $orderMap
                $result.ReadingOrderNormalizedMap = $normalizedOrderMap
            }
        }
    }
    catch {
        $result.MetadataWarning = '元数据.json 解析失败，仅影响简介显示：' + $_.Exception.Message
    }
    return [pscustomobject]$result
}

function Get-ComicAudit {
    param([System.IO.DirectoryInfo]$ComicDirectory)

    $errors = New-Object 'System.Collections.Generic.List[string]'
    $warnings = New-Object 'System.Collections.Generic.List[string]'
    $coverFile = Get-CoverFile -ComicPath $ComicDirectory.FullName
    $coverPath = ''
    $coverRelativeHref = ''
    $coverIsAutomatic = $false
    if ($null -ne $coverFile) {
        if ($coverFile.Length -eq 0) {
            $errors.Add(($coverFile.Name + ' 是空文件'))
        }
        else {
            $coverPath = $coverFile.FullName
            $coverRelativeHref = ConvertTo-UrlSegment $coverFile.Name
        }
    }

    $metadata = Get-ComicMetadata -ComicPath $ComicDirectory.FullName
    $chapterDrafts = @()
    $allDirs = @(Get-ChildItem -LiteralPath $ComicDirectory.FullName -Directory)
    foreach ($dir in $allDirs) {
        $hasChapterImages = @(Get-ChildItem -LiteralPath $dir.FullName -File -ErrorAction SilentlyContinue | Where-Object {
            $script:ImageExtensions -contains $_.Extension.ToLowerInvariant() -and $_.BaseName -ine 'cover'
        }).Count -gt 0
        $numberInfo = Get-ChapterNumberFromName -Name $dir.Name
        $normalizedDirectoryName = Get-WindowsChapterNameMatchKey -Value $dir.Name
        $isMetadataChapter = $metadata.ReadingOrderEnabled -and (
            $metadata.ReadingOrderMap.ContainsKey($dir.Name) -or
            $metadata.ReadingOrderNormalizedMap.ContainsKey($normalizedDirectoryName)
        )
        if (-not $hasChapterImages -and -not $isMetadataChapter) {
            $warnings.Add(('已忽略不含漫画图片的子文件夹：' + $dir.Name))
            continue
        }
        $isNumeric = ($null -ne $numberInfo)
        $hasQualifier = $isNumeric -and [bool]$numberInfo.HasQualifier
        $chapterDrafts += [pscustomobject]@{
            IsRootChapter = $false
            ImageFiles = $null
            IsNumeric = $isNumeric
            Number = if ($isNumeric) { $numberInfo.Text } else { '' }
            HasQualifier = $hasQualifier
            QualifierKey = if ($hasQualifier) { $numberInfo.QualifierKey } else { '' }
            SortGroup = if ($isNumeric) { 0 } else { 1 }
            SortNumber = if ($isNumeric) { $numberInfo.Value } else { [decimal]0 }
            ChapterLabel = if ($isNumeric -and -not $hasQualifier) { '第 ' + $numberInfo.Text + ' 话' } else { $dir.Name }
            ReaderStem = if ($isNumeric -and -not $hasQualifier) { '第' + $numberInfo.Text + '话' } else { $dir.Name }
            Name = $dir.Name
            NaturalSortKey = Get-NaturalNameSortKey -Name $dir.Name
            FullName = $dir.FullName
        }
    }

    $rootImageFiles = @(Get-RootBodyImageFiles -ComicPath $ComicDirectory.FullName)
    $rootLayout = Get-RootImageLayout -Files $rootImageFiles
    $rootCoverCandidate = $null
    if ($chapterDrafts.Count -gt 0 -and $rootImageFiles.Count -gt 0) {
        $errors.Add('漫画根目录中有正文图片，同时又存在章节文件夹；结构有歧义，请只保留一种正文结构。')
    }
    elseif ($chapterDrafts.Count -eq 0 -and $rootImageFiles.Count -gt 0) {
        if ($rootLayout.Recognized) {
            foreach ($group in $rootLayout.Groups) {
                $chapterDrafts += [pscustomobject]@{
                    IsRootChapter = $true
                    ImageFiles = @($group.Files)
                    IsNumeric = $false
                    Number = ''
                    HasQualifier = $false
                    QualifierKey = ''
                    SortGroup = 1
                    SortNumber = [decimal]0
                    ChapterLabel = $group.Name
                    ReaderStem = $group.Name
                    Name = $group.Name
                    NaturalSortKey = $group.NaturalSortKey
                    FullName = $ComicDirectory.FullName
                }
            }
            $rootCoverCandidate = $rootLayout.CoverCandidate
            $warnings.Add(('根目录图片已按文件名前缀拆分为 {0} 话；无元数据时按分组名称自然排序。' -f $rootLayout.Groups.Count))
        }
        else {
            $chapterDrafts += [pscustomobject]@{
                IsRootChapter = $true
                ImageFiles = @($rootImageFiles)
                IsNumeric = $true
                Number = '1'
                HasQualifier = $false
                QualifierKey = ''
                SortGroup = 0
                SortNumber = [decimal]1
                ChapterLabel = '第 1 话'
                ReaderStem = '第1话'
                Name = '第1话'
                NaturalSortKey = Get-NaturalNameSortKey -Name '第1话'
                FullName = $ComicDirectory.FullName
            }
            $warnings.Add('未找到章节文件夹，已将漫画根目录中的图片作为第 1 话。')
        }
    }

    if ($chapterDrafts.Count -eq 0) {
        $errors.Add('没有可识别的章节')
    }
    else {
        $sameNumberGroups = @($chapterDrafts | Where-Object IsNumeric | Group-Object Number | Where-Object { $_.Count -gt 1 })
        foreach ($numberGroup in $sameNumberGroups) {
            $plainChapters = @($numberGroup.Group | Where-Object { -not $_.HasQualifier })
            if ($plainChapters.Count -gt 1) {
                $errors.Add(('章节编号重复：第 {0} 话（{1}）' -f $numberGroup.Name, (($plainChapters | ForEach-Object Name) -join '、')))
            }
            $duplicateQualifiers = @($numberGroup.Group | Where-Object HasQualifier | Group-Object QualifierKey | Where-Object { $_.Count -gt 1 })
            foreach ($duplicateQualifier in $duplicateQualifiers) {
                $errors.Add(('章节编号和分段名称重复：第 {0} 话（{1}）' -f $numberGroup.Name, (($duplicateQualifier.Group | ForEach-Object Name) -join '、')))
            }
        }
        $numericDrafts = @($chapterDrafts | Where-Object IsNumeric | Sort-Object SortNumber, Name)
        if ($numericDrafts.Count -gt 0) {
            if ($numericDrafts[0].SortNumber -ne [decimal]1) {
                $errors.Add(('第一话编号应为 1，实际为 {0}' -f $numericDrafts[0].Number))
            }
            $maxChapter = [int][decimal]::Floor($numericDrafts[-1].SortNumber)
            $chapterNumberMap = @{}
            foreach ($draft in $numericDrafts) { $chapterNumberMap[$draft.Number] = $true }
            for ($number = 1; $number -le $maxChapter; $number++) {
                $integerKey = $number.ToString([Globalization.CultureInfo]::InvariantCulture)
                if (-not $chapterNumberMap.ContainsKey($integerKey)) {
                    $errors.Add(('缺少章节编号：第 {0} 话' -f $number))
                }
            }
        }
    }

    $chapters = @()
    $totalImages = 0
    foreach ($draft in @($chapterDrafts | Sort-Object NaturalSortKey, Name)) {
        $imageFiles = @(if ($draft.IsRootChapter) {
            @($draft.ImageFiles)
        }
        else {
            Get-ChildItem -LiteralPath $draft.FullName -File | Where-Object {
                $script:ImageExtensions -contains $_.Extension.ToLowerInvariant()
            }
        })
        if ($imageFiles.Count -eq 0) {
            $errors.Add(('{0}：没有图片' -f $draft.Name))
            continue
        }

        $sequence = Get-FlexibleImageSequence -Files $imageFiles -Context $draft.Name
        foreach ($problem in $sequence.Errors) { $errors.Add($problem) }
        foreach ($warning in $sequence.Warnings) { $warnings.Add($warning) }
        $sortedImages = @($sequence.Images)
        if ($sortedImages.Count -eq 0) { continue }
        $totalImages += $sortedImages.Count
        $chapters += [pscustomobject]@{
            IsRootChapter = $draft.IsRootChapter
            IsNumeric = $draft.IsNumeric
            Number = $draft.Number
            ChapterLabel = $draft.ChapterLabel
            SortGroup = $draft.SortGroup
            SortNumber = $draft.SortNumber
            ReadingOrder = 0
            Name = $draft.Name
            NaturalSortKey = $draft.NaturalSortKey
            FullName = $draft.FullName
            ReaderFile = if ($draft.ReaderStem -ieq 'index') { '章节-index.html' } else { $draft.ReaderStem + '.html' }
            Key = Get-StableKey -Value ($ComicDirectory.Name + '/' + $draft.Name)
            Images = $sortedImages
            ImageCount = $sortedImages.Count
        }
    }

    if ([string]::IsNullOrWhiteSpace($coverRelativeHref) -and $null -ne $rootCoverCandidate) {
        if ($rootCoverCandidate.Length -eq 0) {
            $errors.Add(($rootCoverCandidate.Name + ' 是空文件'))
        }
        else {
            $coverPath = $rootCoverCandidate.FullName
            $coverRelativeHref = ConvertTo-UrlSegment $rootCoverCandidate.Name
            $coverIsAutomatic = $true
            $warnings.Add(('已将根目录中独立的零号图片作为封面：' + $rootCoverCandidate.Name))
        }
    }

    if ($metadata.MetadataWarning) {
        $warnings.Add($metadata.MetadataWarning)
    }
    if ($metadata.ReadingOrderError) {
        $errors.Add(('无法读取整理器保存的阅读顺序：' + $metadata.ReadingOrderError))
    }
    elseif ($metadata.ReadingOrderEnabled) {
        $missingOrder = @()
        $matchedMetadataFolders = @{}
        foreach ($chapter in $chapters) {
            if ($metadata.ReadingOrderMap.ContainsKey($chapter.Name)) {
                $chapter.ReadingOrder = [int]$metadata.ReadingOrderMap[$chapter.Name]
                $matchedMetadataFolders[$chapter.Name] = $true
            }
            else {
                $normalizedName = Get-WindowsChapterNameMatchKey -Value $chapter.Name
                if ($metadata.ReadingOrderNormalizedMap.ContainsKey($normalizedName)) {
                    $matchedEntry = $metadata.ReadingOrderNormalizedMap[$normalizedName]
                    $chapter.ReadingOrder = [int]$matchedEntry.Order
                    $matchedMetadataFolders[[string]$matchedEntry.Folder] = $true
                }
                else {
                    $missingOrder += $chapter.Name
                }
            }
        }
        if ($missingOrder.Count -gt 0) {
            $errors.Add(('整理器阅读顺序缺少以下章节：' + ($missingOrder -join '、')))
        }
        else {
            $chapters = @($chapters | Sort-Object ReadingOrder, SortNumber, Name)
            $staleNames = @($metadata.ReadingOrderMap.Keys | Where-Object { -not $matchedMetadataFolders.ContainsKey($_) })
            if ($staleNames.Count -gt 0) {
                $warnings.Add(('阅读顺序元数据含有已不存在的章节，已忽略：' + ($staleNames -join '、')))
            }
        }
    }
    else {
        $chapters = @($chapters | Sort-Object NaturalSortKey, Name)
    }

    if ([string]::IsNullOrWhiteSpace($coverRelativeHref)) {
        if ($chapters.Count -gt 0 -and $chapters[0].Images.Count -gt 0) {
            $coverChapter = $chapters[0]
            $coverImage = $coverChapter.Images[0]
            $coverPath = $coverImage.FullName
            $coverRelativeHref = Get-ChapterImageHref -Chapter $coverChapter -Image $coverImage
            $coverIsAutomatic = $true
            $coverDisplayPath = if ($coverChapter.IsRootChapter) {
                '[根目录正文]\' + $coverImage.Name
            }
            else {
                $coverChapter.Name + '\' + $coverImage.Name
            }
            $warnings.Add(('未找到 cover.jpg，已自动使用阅读顺序第一章的首张图片作封面：' + $coverDisplayPath))
        }
        else {
            $errors.Add('缺少封面，且没有可作为自动封面的章节首图。')
        }
    }

    return [pscustomobject]@{
        Name = $ComicDirectory.Name
        FullName = $ComicDirectory.FullName
        Key = Get-StableKey -Value $ComicDirectory.Name
        CoverPath = $coverPath
        CoverRelativeHref = $coverRelativeHref
        CoverIsAutomatic = $coverIsAutomatic
        Chapters = @($chapters)
        ChapterCount = $chapters.Count
        TotalImages = $totalImages
        Author = $metadata.Author
        Description = $metadata.Description
        Errors = @($errors)
        Warnings = @($warnings)
        IsValid = ($errors.Count -eq 0)
    }
}

