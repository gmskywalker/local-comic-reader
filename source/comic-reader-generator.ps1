function ConvertTo-ConfigurationObject {
    param([object]$Parsed)
    $openAfterGenerate = $true
    if ($null -ne $Parsed.PSObject.Properties['openAfterGenerate']) {
        $openAfterGenerate = [bool]$Parsed.openAfterGenerate
    }
    return [pscustomobject]@{
        schemaVersion = 3
        selected = @($Parsed.selected | ForEach-Object { [string]$_ })
        openAfterGenerate = $openAfterGenerate
    }
}

function Get-Configuration {
    param([string]$LegacyPath, [string]$LibraryRoot)
    if (-not [string]::IsNullOrWhiteSpace($LegacyPath) -and (Test-Path -LiteralPath $LegacyPath -PathType Leaf)) {
        try {
            $raw = [System.IO.File]::ReadAllText($LegacyPath, [System.Text.Encoding]::UTF8)
            $parsed = $raw | ConvertFrom-Json
            return ConvertTo-ConfigurationObject -Parsed $parsed
        }
        catch {
            throw "旧配置文件无法读取：$LegacyPath`r`n$($_.Exception.Message)"
        }
    }

    $launcherPath = Join-Path $LibraryRoot $script:LauncherFileName
    if (Test-Path -LiteralPath $launcherPath -PathType Leaf) {
        try {
            $html = [System.IO.File]::ReadAllText($launcherPath, [System.Text.Encoding]::UTF8)
            $pattern = '<script\s+type="application/json"\s+id="' + [regex]::Escape($script:EmbeddedConfigElementId) + '">(.*?)</script>'
            $match = [regex]::Match($html, $pattern, [Text.RegularExpressions.RegexOptions]::Singleline)
            if ($match.Success) {
                $parsed = $match.Groups[1].Value | ConvertFrom-Json
                return ConvertTo-ConfigurationObject -Parsed $parsed
            }
        }
        catch {
            throw "漫画阅读器内嵌配置无法读取：$launcherPath`r`n$($_.Exception.Message)"
        }
    }

    $selected = @()
    foreach ($name in $script:DefaultSelected) {
        if (Test-Path -LiteralPath (Join-Path $LibraryRoot $name) -PathType Container) {
            $selected += $name
        }
    }
    return [pscustomobject]@{
        schemaVersion = 3
        selected = $selected
        openAfterGenerate = $true
    }
}

function Get-FolderCandidate {
    param([System.IO.DirectoryInfo]$Directory)
    $reasons = New-Object 'System.Collections.Generic.List[string]'
    $cover = Get-CoverFile -ComicPath $Directory.FullName
    $chapterDirs = @(Get-ChildItem -LiteralPath $Directory.FullName -Directory -ErrorAction SilentlyContinue)
    $metadata = Get-ComicMetadata -ComicPath $Directory.FullName
    $matching = @($chapterDirs | Where-Object {
        $hasImages = @(Get-ChildItem -LiteralPath $_.FullName -File -ErrorAction SilentlyContinue | Where-Object {
            $script:ImageExtensions -contains $_.Extension.ToLowerInvariant() -and $_.BaseName -ine 'cover'
        }).Count -gt 0
        $normalizedName = Get-WindowsChapterNameMatchKey -Value $_.Name
        $hasImages -or ($metadata.ReadingOrderEnabled -and (
            $metadata.ReadingOrderMap.ContainsKey($_.Name) -or
            $metadata.ReadingOrderNormalizedMap.ContainsKey($normalizedName)
        ))
    })
    $rootImages = @(Get-RootBodyImageFiles -ComicPath $Directory.FullName)
    $usesRootImages = ($matching.Count -eq 0 -and $rootImages.Count -gt 0)
    $rootLayout = if ($usesRootImages) { Get-RootImageLayout -Files $rootImages } else { $null }
    if ($matching.Count -gt 0 -and $rootImages.Count -gt 0) {
        $reasons.Add('根目录正文图片与章节文件夹同时存在，结构有歧义')
    }
    elseif ($matching.Count -eq 0 -and $rootImages.Count -eq 0) {
        $reasons.Add('没有包含漫画图片的章节文件夹或根目录正文图片')
    }
    return [pscustomobject]@{
        Name = $Directory.Name
        FullName = $Directory.FullName
        Eligible = ($reasons.Count -eq 0)
        ChapterCount = if ($usesRootImages -and $null -ne $rootLayout -and $rootLayout.Recognized) { $rootLayout.Groups.Count } elseif ($usesRootImages) { 1 } else { $matching.Count }
        UsesRootImages = $usesRootImages
        UsesCompositeGroups = ($usesRootImages -and $null -ne $rootLayout -and $rootLayout.Recognized)
        HasCover = ($null -ne $cover)
        Reason = ($reasons -join '；')
    }
}

function Get-AllCandidates {
    param([string]$LibraryRoot)
    $items = @()
    foreach ($dir in @(Get-ChildItem -LiteralPath $LibraryRoot -Directory | Sort-Object Name)) {
        if ($dir.Name -ieq 'new' -and (
            (Test-Path -LiteralPath (Join-Path $dir.FullName 'comic-organizer.ps1') -PathType Leaf) -or
            (Test-Path -LiteralPath (Join-Path $dir.FullName '漫画整理器.bat') -PathType Leaf) -or
            (Test-Path -LiteralPath (Join-Path $dir.FullName '漫画整理器.vbs') -PathType Leaf)
        )) {
            continue
        }
        $items += Get-FolderCandidate -Directory $dir
    }
    return @($items)
}

function Resolve-UpdateSelection {
    param(
        [string[]]$PreviousNames,
        [string[]]$CheckedNames,
        [ValidateSet('All', 'AddOnly')][string]$UpdateMode
    )
    $previous = @($PreviousNames | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Select-Object -Unique)
    $checked = @($CheckedNames | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Select-Object -Unique)
    if ($UpdateMode -eq 'AddOnly') {
        $newNames = @($checked | Where-Object { $previous -notcontains $_ })
        return [pscustomobject]@{
            SelectedNames = @($previous + $newNames | Select-Object -Unique)
            NamesToGenerate = @($newNames)
        }
    }
    return [pscustomobject]@{
        SelectedNames = @($checked)
        NamesToGenerate = @($checked)
    }
}

function ConvertTo-MetadataPlainText {
    param([AllowNull()][object]$Value)
    if ($null -eq $Value) { return '' }
    $parts = @($Value | ForEach-Object {
        if ($_ -is [string]) { $_ }
        elseif ($null -ne $_.PSObject.Properties['name']) { [string]$_.name }
        elseif ($null -ne $_.PSObject.Properties['title']) { [string]$_.title }
        else { [string]$_ }
    })
    $text = ($parts -join "`r`n").Trim()
    if ([string]::IsNullOrWhiteSpace($text)) { return '' }
    $text = [regex]::Replace($text, '(?is)<\s*br\s*/?\s*>', "`n")
    $text = [regex]::Replace($text, '(?is)</\s*(?:p|div|li|tr|h[1-6])\s*>', "`n")
    $text = [regex]::Replace($text, '(?is)<\s*li(?:\s[^>]*)?>', '• ')
    $text = [regex]::Replace($text, '(?is)<[^>]+>', '')
    $text = [Net.WebUtility]::HtmlDecode($text)
    $lines = @(($text -replace "`r`n?", "`n") -split "`n" | ForEach-Object { ([regex]::Replace($_, '[\t ]+', ' ')).Trim() })
    return (($lines -join "`r`n").Trim())
}

function Get-MetadataFieldText {
    param(
        [AllowNull()][object]$Metadata,
        [string[]]$Names
    )
    if ($null -eq $Metadata) { return '' }
    foreach ($name in $Names) {
        $property = $Metadata.PSObject.Properties[$name]
        if ($null -eq $property) { continue }
        $text = ConvertTo-MetadataPlainText -Value $property.Value
        if (-not [string]::IsNullOrWhiteSpace($text)) { return $text }
    }
    return ''
}

